// Id de pedido (UUID v4) para operações idempotentes: o mesmo id em um retry não repete a operação no servidor.
// Não é segredo, só precisa ser único por pedido.
export function requestId(): string {
  const h = Array.from({ length: 32 }, () => Math.floor(Math.random() * 16).toString(16));
  h[12] = '4';
  h[16] = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  const s = h.join('');
  return `${s.slice(0, 8)}-${s.slice(8, 12)}-${s.slice(12, 16)}-${s.slice(16, 20)}-${s.slice(20)}`;
}
